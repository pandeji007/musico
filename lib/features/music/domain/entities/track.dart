class Track {
  final int id;
  final String name;
  final int duration;
  final String artistName;
  final String albumName;
  final String albumImage;
  final String image;
  final String audio;

  const Track({
    required this.id,
    required this.name,
    required this.duration,
    required this.artistName,
    required this.albumName,
    required this.albumImage,
    required this.image,
    required this.audio,
  });
}
